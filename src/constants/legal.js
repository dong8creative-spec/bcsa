/**
 * 광고성 정보를 보내도 되는지 (발송 기능을 만들 때 반드시 이 함수로 거른다)
 * 동의 일시가 기록된 경우만 동의로 본다. 예전 marketingAgreed만 있는 회원은 '미확인'이라 보내지 않는다.
 */
export const getMarketingConsentState = (user) => {
  const mc = user?.marketingConsent;
  if (mc && typeof mc === 'object' && mc.agreedAt && mc.agreed === true && Array.isArray(mc.channels) && mc.channels.length > 0) {
    return { status: 'agreed', channels: mc.channels, consent: mc };
  }
  if (mc && typeof mc === 'object' && (mc.withdrawnAt || mc.agreed === false)) {
    return { status: 'declined', channels: [], consent: mc };
  }
  if (user?.marketingAgreed === true) return { status: 'unverified', channels: [], consent: null };
  return { status: 'none', channels: [], consent: null };
};

